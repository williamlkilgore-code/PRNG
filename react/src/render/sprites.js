export const SPRITES = S;

// Which sprite to draw for a map object.
export function objectSprite(o) {
  switch (o.type) {
    case 'enemy': return o.kind || 'rat';
    case 'mimic': return 'mimicChest';
    case 'lock': return o.mimic ? 'mimicDoor' : 'lock';
    case 'medpack': return 'potion';
    default: return S[o.type] ? o.type : null;
  }
}
export const heroSprite = (cls) => cls || 'hero';

/* ---- drawing ---- */
const cache = new Map();

// A canvas holding one sprite at 1 pixel per pixel (tinted if asked).
export function spriteCanvas(id, tint) {
  const key = id + ':' + (tint || '');
  if (cache.has(key)) return cache.get(key);
  const rows = S[id];
  if (!rows || typeof document === 'undefined') return null;
  const cv = document.createElement('canvas');
  cv.width = 16; cv.height = 16;
  const ctx = cv.getContext('2d');
  const [C, D] = TINTS[tint] || TINTS.gold;
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const ch = rows[y][x];
      if (ch === '.' || ch === undefined) continue;
      ctx.fillStyle = ch === 'C' ? C : ch === 'D' ? D : PAL[ch] || '#ff00ff';
      ctx.fillRect(x, y, 1, 1);
    }
  }
  cache.set(key, cv);
  return cv;
}

// A data: URL for <img> tags (HUD, battle screen, menus).
const urlCache = new Map();
export function spriteUrl(id, tint) {
  const key = id + ':' + (tint || '');
  if (!urlCache.has(key)) {
    const cv = spriteCanvas(id, tint);
    urlCache.set(key, cv ? cv.toDataURL() : '');
  }
  return urlCache.get(key);
}

// An optional external sprite sheet (see SHEET above).
let sheetImg = null;
export function loadSheet() {
  if (!SHEET.src || sheetImg) return Promise.resolve();
  return new Promise((res) => {
    const img = new Image();
    img.onload = () => { sheetImg = img; res(); };
    img.onerror = () => res();
    img.src = SHEET.src;
  });
}

export function drawSprite(ctx, id, x, y, size, tint) {
  const at = sheetImg && SHEET.map[id];
  if (at) {
    ctx.drawImage(sheetImg, at[0] * SHEET.tile, at[1] * SHEET.tile, SHEET.tile, SHEET.tile, x, y, size, size);
    return;
  }
  const cv = spriteCanvas(id, tint);
  if (cv) ctx.drawImage(cv, x, y, size, size);
}
